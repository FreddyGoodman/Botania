package org.violetmoon.botania.client.patchouli;

import net.minecraft.client.Minecraft;
import net.minecraft.resources.Identifier;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.crafting.*;
import net.minecraft.world.level.Level;

import org.jetbrains.annotations.Nullable;
import org.violetmoon.botania.api.BotaniaAPI;
import org.violetmoon.botania.api.recipe.StateIngredient;
import org.violetmoon.botania.common.crafting.BotaniaRecipeTypes;
import org.violetmoon.botania.xplat.XplatAbstractions;

import vazkii.patchouli.api.IVariable;

import java.util.*;
import java.util.stream.Collectors;

public class PatchouliUtils {
	private static boolean crafttweakerInfoNote = false;
	private static boolean inVisualizer;

	/**
	 * Gets a recipe of a specified type and ID, and replaces the namespace
	 * with {@code crafttweaker} to try and find replacements if the recipe doesn't exist.
	 * If the recipe has no replacement, it will be logged.
	 */
	@Nullable
	public static <T extends Recipe<C>, C extends RecipeInput> T getRecipe(Level level, RecipeType<T> type, Identifier id) {
		// TODO: This can probably be removed/simplified
		Optional<RecipeHolder<T>> directRecipe = BotaniaRecipeTypes.getRecipe(level, id, type);
		if (directRecipe.isPresent()) {
			return directRecipe.get().value();
		}
		Optional<RecipeHolder<T>> craftTweakerRecipe = BotaniaRecipeTypes.getRecipe(level,
				Identifier.fromNamespaceAndPath("crafttweaker", id.getPath()), type);
		if (craftTweakerRecipe.isPresent()) {
			return craftTweakerRecipe.get().value();
		}
		Optional<RecipeHolder<T>> craftTweakerGeneratedRecipe = BotaniaRecipeTypes.getRecipe(level,
				Identifier.fromNamespaceAndPath("crafttweaker",
						"autogenerated/" + id.getNamespace() + "." + id.getPath()),
				type);
		if (craftTweakerGeneratedRecipe.isPresent()) {
			return craftTweakerGeneratedRecipe.get().value();
		}

		BotaniaAPI.LOGGER.warn("Template references nonexistent recipe {} of type {}", id, type);
		if (!crafttweakerInfoNote) {
			crafttweakerInfoNote = true;
			if (XplatAbstractions.INSTANCE.isModLoaded("crafttweaker")) {
				BotaniaAPI.LOGGER.info("""
					To add a recipe that replaces a builtin recipe with CT,\s
					add one with the same type, named the same as the path of the missing recipe.
					eg. for recipe {}, add a recipe named "{}".""", id, id.getPath());
			}
		}
		return null;
	}

	/**
	 * Get all recipes of the specified type that belong to the specified recipe group.
	 */
	public static <T extends Recipe<C>, C extends RecipeInput> List<T> getRecipeGroup(RecipeType<T> type, String group) {
		List<T> list = new ArrayList<>();
		for (RecipeHolder<T> holder : BotaniaRecipeTypes.recipes(Minecraft.getInstance().level).byType(type)) {
			T recipe = holder.value();
			if (group.equals(recipe.group())) {
				list.add(recipe);
			}
		}
		if (list.isEmpty()) {
			BotaniaAPI.LOGGER.warn("Template references empty group {} of recipe type {}", group, type);
		}
		return list;
	}

	public static List<ItemStack> displayStacks(@Nullable Ingredient ingredient, Level level) {
		return ingredient == null ? List.of() : ingredient.display().resolveForStacks(SlotDisplayContext.fromLevel(level));
	}

	public static IVariable interweaveIngredients(List<Ingredient> ingredients, int longestIngredientSize, Level level) {
		return interweaveStacks(ingredients.stream().map(ingredient -> displayStacks(ingredient, level)).toList(), longestIngredientSize, level);
	}

	public static IVariable interweaveIngredients(List<Ingredient> ingredients, Level level) {
		var stacks = ingredients.stream().map(ingredient -> displayStacks(ingredient, level)).toList();
		int longest = stacks.stream().mapToInt(List::size).max().orElse(1);
		return interweaveStacks(stacks, longest, level);
	}

	/**
	 * Cycles the stacks in each recipe column together so that alternatives stay aligned across the page.
	 */
	public static IVariable interweaveStacks(List<List<ItemStack>> stacks, int longestIngredientSize, Level level) {
		var registries = level.registryAccess();
		if (stacks.size() == 1) {
			return IVariable.wrapList(stacks.getFirst().stream().map(stack -> IVariable.from(stack, registries)).toList(), registries);
		}

		List<IVariable> values = new ArrayList<>(stacks.size() * longestIngredientSize);
		for (int cycle = 0; cycle < longestIngredientSize; cycle++) {
			for (List<ItemStack> options : stacks) {
				ItemStack stack = options.isEmpty() ? ItemStack.EMPTY : options.get(cycle % options.size());
				values.add(IVariable.from(stack, registries));
			}
		}
		return IVariable.wrapList(values, registries);
	}

	public static IVariable interweaveStateIngredients(List<StateIngredient> ingredients, Level level) {
		var stacks = ingredients.stream().map(ingredient -> ingredient != null ? ingredient.getDisplayedStacks() : List.<ItemStack>of()).toList();
		int longest = Math.max(1, stacks.stream().mapToInt(List::size).max().orElse(0));
		return interweaveStacks(stacks, longest, level);
	}

	/**
	 * Workaround for Patchouli limitation - Allow block entity-rendered blocks to detect being rendered in
	 * a multiblock visualization and switch to block model rendering to actually be visible.
	 */
	public static boolean isInVisualizer() {
		return inVisualizer;
	}

	public static void setInVisualizer(boolean inVisualization) {
		PatchouliUtils.inVisualizer = inVisualization;
	}
}
